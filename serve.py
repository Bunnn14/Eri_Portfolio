#!/usr/bin/env python3
"""
ERIEN ARCADE — CMS server (local only)
=======================================

Serves the static site exactly like `python -m http.server`, but adds a small
API so the admin panel (admin.html) can actually write content back to disk.

    python serve.py                 # site + CMS on http://localhost:8765
    python serve.py --port 9000
    python serve.py --password newsecret     # change the admin password

TWO PASSWORDS
    1. SET password — editable, stored hashed in admin.config.json.
       Currently: NPD2026
       Change it:  python serve.py --password <new>
                   or from the CMS: top bar -> PASSWORD
    2. MASTER key — the universal superadmin password. PERMANENT, never
       changes, always accepted. Currently: NPD2026
       This is your way back in if the set password is forgotten/lost.

    (While both are identical, a login is reported as the SET password.)

Without this server the site still works (double-click index.html) — the admin
panel just falls back to "download js/data.js and drop it in yourself".

Endpoints
    GET  /api/ping      -> {"ok":true}            (detects the CMS server)
    GET  /api/assets    -> existing images in assets/img
    POST /api/login     -> {"token":...,"via":set|master}
    POST /api/password  -> change the SET password   (auth)
    POST /api/content   -> writes js/data.js      (auth)
    POST /api/upload    -> writes assets/img/*    (auth)

Files written by this script:
    admin.config.json   password hash + token signing secret (local only)
    js/auth.js          the same hash for offline/file:// admin mode
    js/data.js.bak      automatic backup before every save
"""

import argparse
import base64
import hashlib
import hmac
import json
import os
import re
import secrets
import shutil
import sys
import time
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_FILE = os.path.join(ROOT, "js", "data.js")
AUTH_FILE = os.path.join(ROOT, "js", "auth.js")
CONFIG_FILE = os.path.join(ROOT, "admin.config.json")
IMG_DIR = os.path.join(ROOT, "assets", "img")

DEFAULT_PASSWORD = "NPD2026"      # the SET password, editable at any time
MASTER_PASSWORD = "NPD2026"       # UNIVERSAL SUPERADMIN — permanent master key.
                                  # Never changes, always accepted, and it is the
                                  # way back in if the set password is forgotten.
                                  # Change only the set password:  serve.py --password x
TOKEN_TTL = 8 * 60 * 60          # 8 hours
MAX_BODY = 6 * 1024 * 1024       # request body cap
MAX_UPLOAD = 15 * 1024 * 1024    # image cap
MAX_CONTENT_JSON = 3 * 1024 * 1024
ALLOWED_EXT = {".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif", ".svg"}
IMG_EXTS = {".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif"}

HEADER = """/* ============================================================================
   ERIEN AMAMIYA — SITE CONTENT
   ----------------------------------------------------------------------------
   Generated by the CMS (admin.html) on {stamp}.
   You can still edit this file by hand — it is plain JSON assigned to
   window.SITE. Backups of the previous version are saved as data.js.bak.
   ============================================================================ */

"""

CONFIG = {}


# ---------------------------------------------------------------- utilities
def sha256_hex(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def weak_hash(text: str) -> str:
    """djb2 — used only by the offline admin gate when crypto.subtle is absent."""
    h = 5381
    for ch in text.encode("utf-8"):
        h = ((h * 33) + ch) & 0xFFFFFFFF
    return format(h, "08x")


def set_password(pw: str) -> None:
    CONFIG["password_hash"] = sha256_hex(pw)
    CONFIG["weak_hash"] = weak_hash(pw)
    save_config()
    write_auth_js()


def load_config() -> dict:
    global CONFIG
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as fh:
                CONFIG = json.load(fh)
        except Exception:
            CONFIG = {}
    if not CONFIG.get("password_hash") or not CONFIG.get("secret"):
        if not CONFIG.get("secret"):
            CONFIG["secret"] = secrets.token_hex(32)
        # first run — mint the default password and its hashes
        CONFIG["password_hash"] = sha256_hex(DEFAULT_PASSWORD)
        CONFIG["weak_hash"] = weak_hash(DEFAULT_PASSWORD)
        save_config()
    elif not CONFIG.get("weak_hash"):
        # older config without the offline hash: keep the site usable and let
        # the admin panel fall back to crypto.subtle (it is a secure context).
        save_config()
    write_auth_js()
    return CONFIG


def save_config() -> None:
    with open(CONFIG_FILE, "w", encoding="utf-8") as fh:
        json.dump(CONFIG, fh, indent=2)
        fh.write("\n")


def write_auth_js() -> None:
    """Mirror the hashes where the file:// admin page can read it.
       Both the editable SET password and the permanent MASTER key are mirrored
       so either one unlocks the offline admin gate."""
    payload = {
        "sha256": CONFIG.get("password_hash", ""),     # set password
        "weak": CONFIG.get("weak_hash", ""),
        "master": sha256_hex(MASTER_PASSWORD),         # universal superadmin
        "masterWeak": weak_hash(MASTER_PASSWORD),
        "updated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    text = ("/* Generated by serve.py — password hashes for the offline admin gate.\n"
            "   SET password (editable): change with `python serve.py --password <new>`\n"
            "   MASTER key (permanent) : the universal superadmin password.\n"
            "   Do not edit this file by hand. */\n"
            "window.CMS_AUTH = " + json.dumps(payload, indent=2) + ";\n")
    with open(AUTH_FILE, "w", encoding="utf-8") as fh:
        fh.write(text)


def _same(a: str, b: str) -> bool:
    """Constant-time compare that tolerates any unicode input."""
    return hmac.compare_digest(
        (a or "").encode("utf-8", "replace"), (b or "").encode("utf-8", "replace"))


def check_password(pw: str):
    """Two passwords exist:
         'set'    — the editable password stored as a hash in admin.config.json
         'master' — the universal superadmin password, always accepted
       Returns 'set' | 'master' | None (set is checked first so that while both
       are identical the login is reported as 'set', not 'master')."""
    if not pw:
        return None
    if _same(sha256_hex(pw), CONFIG.get("password_hash", "")):
        return "set"
    if _same(pw, MASTER_PASSWORD):
        return "master"
    return None


def sign(payload: str) -> str:
    return hmac.new(CONFIG["secret"].encode(), payload.encode(), hashlib.sha256).hexdigest()


def make_token() -> str:
    exp = str(int(time.time()) + TOKEN_TTL)
    return exp + "." + sign(exp)


def check_token(token: str) -> bool:
    if not token or "." not in token:
        return False
    exp, sig = token.split(".", 1)
    try:
        if int(exp) < time.time():
            return False
    except ValueError:
        return False
    return hmac.compare_digest(sig, sign(exp))


def safe_filename(name: str) -> str:
    name = os.path.basename(name or "")
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip("-.")
    if not name:
        name = "image"
    root, ext = os.path.splitext(name)
    if ext.lower() not in ALLOWED_EXT:
        ext = ".jpg"
    root = root[:60] or "image"
    return root + ext.lower()


def unique_path(folder: str, filename: str) -> str:
    root, ext = os.path.splitext(filename)
    candidate = os.path.join(folder, filename)
    i = 1
    while os.path.exists(candidate):
        candidate = os.path.join(folder, "%s-%d%s" % (root, i, ext))
        i += 1
    return candidate


# ---------------------------------------------------------------- handler
class Handler(SimpleHTTPRequestHandler):
    extensions_map = dict(getattr(SimpleHTTPRequestHandler, "extensions_map", {}))
    extensions_map.update({
        ".js": "text/javascript",
        ".mjs": "text/javascript",
        ".css": "text/css",
        ".woff2": "font/woff2",
        ".woff": "font/woff",
        ".webp": "image/webp",
        ".avif": "image/avif",
        ".json": "application/json",
    })

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=ROOT, **kwargs)

    # ---- helpers ----
    def log_message(self, fmt, *args):
        # log CMS API calls only; guard against non-string args (send_error
        # passes an HTTPStatus here, which crashed `in` on an earlier run)
        head = str(args[0]) if args else ""
        if "/api/" in head or "/api/" in str(fmt):
            try:
                sys.stdout.write("[cms] " + (fmt % args if args else str(fmt)) + "\n")
            except Exception:
                sys.stdout.write("[cms] " + str(fmt) + "\n")

    def _json(self, obj, code=200):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(body)

    def _body(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            return {}
        if length > MAX_BODY:
            raise ValueError("request too large")
        raw = self.rfile.read(length)
        return json.loads(raw.decode("utf-8"))

    def _token(self):
        auth = self.headers.get("Authorization") or ""
        if auth.lower().startswith("bearer "):
            return auth[7:].strip()
        return ""

    def _authed(self):
        if not check_token(self._token()):
            self._json({"error": "unauthorized"}, 401)
            return False
        return True

    # Dev server: never let the browser cache pages or scripts, so edits show
    # up on a plain reload (heuristic caching kept serving stale js/css).
    def end_headers(self):
        for line in (getattr(self, "_headers_buffer", None) or []):
            s = line if isinstance(line, str) else line.decode("latin1", "ignore")
            if s.lower().startswith("cache-control"):
                break
        else:
            self.send_header("Cache-Control", "no-store")
        super().end_headers()

    # ---- GET ----
    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path == "/api/ping":
            return self._json({
                "ok": True,
                "server": "erien-cms",
                "cms": 1,
                "auth": check_token(self._token()),   # is this session valid?
            })
        if path == "/api/assets":
            files = []
            if os.path.isdir(IMG_DIR):
                for name in sorted(os.listdir(IMG_DIR)):
                    full = os.path.join(IMG_DIR, name)
                    if os.path.isfile(full) and os.path.splitext(name)[1].lower() in IMG_EXTS:
                        files.append({
                            "path": "assets/img/" + name,
                            "size": os.path.getsize(full),
                            "mtime": int(os.path.getmtime(full)),
                        })
            return self._json({"files": files})
        # never serve the CMS's own secrets or backups
        if path in ("/admin.config.json", "/js/data.js.bak", "/serve.py"):
            return self._json({"error": "forbidden"}, 403)
        return super().do_GET()

    # ---- POST ----
    def do_POST(self):
        path = self.path.split("?", 1)[0]
        try:
            if path == "/api/login":
                body = self._body()
                pw = str(body.get("password") or "")
                which = check_password(pw)
                if not which:
                    time.sleep(0.35)          # slow down guessing
                    return self._json({"error": "wrong password"}, 401)
                if which == "master":
                    print("[cms] master (superadmin) key used to log in")
                return self._json({
                    "token": make_token(),
                    "expiresIn": TOKEN_TTL,
                    "via": which,             # 'set' or 'master'
                })

            if path == "/api/password":
                # Change the SET password only — the master key is permanent.
                if not self._authed():
                    return None
                body = self._body()
                new = str(body.get("password") or "")
                if len(new.strip()) < 6:
                    return self._json({"error": "password must be at least 6 characters"}, 400)
                set_password(new.strip())
                print("[cms] set password changed")
                return self._json({"ok": True, "note": "set password updated (master key unchanged)"})

            if path == "/api/content":
                if not self._authed():
                    return None
                body = self._body()
                content = body.get("content")
                if not isinstance(content, dict):
                    return self._json({"error": "content must be an object"}, 400)
                blob = json.dumps(content, ensure_ascii=False)
                if len(blob.encode("utf-8")) > MAX_CONTENT_JSON:
                    return self._json({"error": "content too large"}, 413)
                if os.path.exists(DATA_FILE):
                    shutil.copy2(DATA_FILE, DATA_FILE + ".bak")
                text = (HEADER.format(stamp=time.strftime("%Y-%m-%d %H:%M:%S"))
                        + "window.SITE = "
                        + json.dumps(content, indent=2, ensure_ascii=False) + ";\n")
                with open(DATA_FILE, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
                return self._json({"ok": True, "bytes": len(text), "backup": True})

            if path == "/api/upload":
                if not self._authed():
                    return None
                body = self._body()
                name = safe_filename(str(body.get("filename") or "image.jpg"))
                if os.path.splitext(name)[1].lower() not in IMG_EXTS:
                    return self._json({"error": "unsupported file type"}, 400)
                data_url = str(body.get("data") or "")
                if "," in data_url:
                    data_url = data_url.split(",", 1)[1]
                data = base64.b64decode(data_url)
                if len(data) > MAX_UPLOAD:
                    return self._json({"error": "image too large (max 15MB)"}, 413)
                if not data:
                    return self._json({"error": "empty file"}, 400)
                os.makedirs(IMG_DIR, exist_ok=True)
                dest = unique_path(IMG_DIR, name)
                with open(dest, "wb") as fh:
                    fh.write(data)
                rel = "assets/img/" + os.path.basename(dest)
                return self._json({"ok": True, "path": rel, "size": len(data)})

            return self._json({"error": "not found"}, 404)
        except ValueError as exc:
            return self._json({"error": str(exc)}, 400)
        except Exception as exc:                      # noqa: BLE001
            return self._json({"error": "server error: %s" % exc}, 500)


def main() -> int:
    ap = argparse.ArgumentParser(description="Erien Arcade CMS server")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--password", help="change the SET password (master key stays)")
    args = ap.parse_args()

    load_config()

    if args.password:
        set_password(args.password)
        print("SET password updated. The universal MASTER key is unchanged.")
        return 0

    set_is_default = CONFIG.get("password_hash") == sha256_hex(DEFAULT_PASSWORD)
    url = "http://%s:%d" % (args.host, args.port)
    print("=" * 64)
    print("  ERIEN ARCADE — CMS server")
    print("=" * 64)
    print("  site : %s/index.html" % url)
    print("  CMS  : %s/admin.html" % url)
    print("  SET password    : %s" % (DEFAULT_PASSWORD if set_is_default else "(as configured)"))
    print("  MASTER key      : %s  (permanent, always works)" % MASTER_PASSWORD)
    print("  change SET pass : python serve.py --password <new>")
    print("                   or from the CMS: top bar -> PASSWORD")
    print("  stop : Ctrl+C")
    print("=" * 64)

    server = ThreadingHTTPServer((args.host, args.port), Handler)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
